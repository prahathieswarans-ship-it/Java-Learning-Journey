package basics.datatypes;

public class LongExercise {
    public static void main(String[] args) {
        long population = 8000000000L;
        long websiteViews = 9876543210L;
        long totalDistance = 123456789012L;
        long oldVisitors = 5000000000L;
        long newVisitors = 2000000000L;
        long totalVisitors = oldVisitors + newVisitors;

        System.out.println("Population: " + population);
        System.out.println("Website Views: " + websiteViews);
        System.out.println("Total Distance: " + totalDistance);
        System.out.println("Total Visitors: " + totalVisitors);

    }
}
